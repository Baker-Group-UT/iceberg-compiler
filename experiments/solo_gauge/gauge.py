# ----------------------------------------------------------------------------------------


def left_kernel(rows: np.ndarray) -> List[np.ndarray]:
    """Basis of {a : a @ rows = 0 (mod 2)} for a boolean matrix `rows` (m x w)."""
    rows = np.asarray(rows, dtype=bool)
    m = rows.shape[0]
    if m == 0:
        return []
    w = rows.shape[1]
    aug = np.concatenate([rows, np.eye(m, dtype=bool)], axis=1)
    pivot = 0
    for col in range(w):
        hits = np.flatnonzero(aug[pivot:, col])
        if not len(hits):
            continue
        r = pivot + int(hits[0])
        aug[[pivot, r]] = aug[[r, pivot]]
        others = np.flatnonzero(aug[:, col])
        for o in others:
            if o != pivot:
                aug[o] ^= aug[pivot]
        pivot += 1
        if pivot == m:
            break
    return [aug[r, w:].copy() for r in range(pivot, m)]


