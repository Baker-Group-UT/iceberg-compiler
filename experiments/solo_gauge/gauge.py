def _records(circuit) -> List[Tuple[str, int]]:
    out: List[Tuple[str, int]] = []
    for instruction in circuit.data:
        if instruction.operation.name.lower() != "measure":
            continue
        for clbit in instruction.clbits:
            register, index = circuit.find_bit(clbit).registers[0]
            out.append((register.name, index))
    return out


def frame_split(circuit, noisy, final_positions: Sequence[Tuple[int, int]],
                checks: Sequence[GaugeCheck], *, shots: int = 100_000,
                seed: Optional[int] = 0) -> Dict[str, float]:
    """
    Noise-only measurement flips (`stim.FlipSimulator`, stabilizer randomization off), read
    the way each decoder reads bits. Unlike `exp8_undetected.frames.split_from_stim`, a
    logical flip counts only on lanes that hold a program qubit at the end: a flipped spare
    is not an output error.
    """
    import stim

    simulator = stim.FlipSimulator(batch_size=shots, disable_stabilizer_randomization=True,
                                   num_qubits=noisy.num_qubits, seed=seed)
    simulator.do(noisy)
    flips = simulator.get_measurement_flips(bit_packed=False)
    rows: Dict[str, Dict[int, int]] = {}
    for row, (name, index) in enumerate(_records(circuit)):
        rows.setdefault(name, {})[index] = row
    if flips.shape[0] != sum(len(v) for v in rows.values()):
        raise ValueError("measurement records and Stim flips disagree in count")

    detected = np.zeros(shots, dtype=bool)
    data_names = sorted((name for name in rows if "data" in name),
                        key=lambda name: int(name.rsplit("_", 1)[1]))
    lane_flip: Dict[int, np.ndarray] = {}
    for name, by_index in rows.items():
        block = flips[[by_index[i] for i in sorted(by_index)]]
        if "parity" in name or "flag" in name:
            detected |= block.any(axis=0)
    for patch, name in enumerate(data_names):
        by_index = rows[name]
        block = flips[[by_index[i] for i in sorted(by_index)]]
        detected |= (block.sum(axis=0) % 2).astype(bool)
        code = CodeLayout(block.shape[0])
        for slot in range(code.k):
            anchor, qubit = code.z_support(slot)
            lane_flip[patch * code.k + slot] = block[anchor] ^ block[qubit]
    k = CodeLayout(len(rows[data_names[0]])).k
    program = np.zeros(shots, dtype=bool)
    for p, s in final_positions:
        program |= lane_flip[int(p) * k + int(s)]
    gauge = np.zeros(shots, dtype=bool)
    for check in checks:
        parity = np.zeros(shots, dtype=bool)
        for lane in check.lanes:
            parity ^= lane_flip[lane]
        gauge |= parity
    detected_412 = detected | gauge
    silent_422 = program & ~detected
    silent_412 = program & ~detected_412
    kept_422 = max(1, int((~detected).sum()))
    kept_412 = max(1, int((~detected_412).sum()))
    newly = gauge & ~detected
    return {
        "frame_shots": int(shots),
        "frame_kept_422": float((~detected).mean()),
        "frame_kept_412": float((~detected_412).mean()),
        "silent_per_kept_422": float(silent_422.sum() / kept_422),
        "silent_per_kept_412": float(silent_412.sum() / kept_412),
        "silent_422": float(silent_422.mean()),
        "silent_412": float(silent_412.mean()),
        #: shots only the gauge check discards, split by whether they carried an output error
        "gauge_caught": float((newly & program).mean()),
        "gauge_harmless": float((newly & ~program).mean()),
    }


