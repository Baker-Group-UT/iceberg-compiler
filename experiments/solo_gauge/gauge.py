def _register_samples(circuit, samples: np.ndarray) -> Dict[str, np.ndarray]:
    """Stim measurement records (shots x records) regrouped as {register: shots x width}."""
    grouped: Dict[str, Dict[int, int]] = {}
    for row, (name, index) in enumerate(_records(circuit)):
        grouped.setdefault(name, {})[index] = row
    return {name: samples[:, [by_index[i] for i in sorted(by_index)]]
            for name, by_index in grouped.items()}


def _check_values(registers: Dict[str, np.ndarray], checks: Sequence[GaugeCheck],
                  n_code: int) -> Tuple[np.ndarray, List[np.ndarray]]:
    """(syndrome fired per shot, [check parity per shot] per check)."""
    layout = CodeLayout(n_code)
    shots = next(iter(registers.values())).shape[0]
    fired = np.zeros(shots, dtype=bool)
    for name, block in registers.items():
        if "parity" in name or "flag" in name:
            fired |= block.any(axis=1)
        elif "data" in name:
            fired |= (block.sum(axis=1) % 2).astype(bool)
    values = []
    for check in checks:
        parity = np.zeros(shots, dtype=bool)
        for lane in check.lanes:
            patch, slot = divmod(lane, layout.k)
            block = registers[f"m_data_{patch}"]
            parity ^= block[:, layout.lane(slot)] ^ block[:, layout.z_anchor]
        values.append(parity)
    return fired, values


def noiseless_gate(circuit, analysis: GaugeAnalysis, *, shots: int = 2000,
                   seed: int = 1) -> Dict[str, int]:
    """
    Sample the translated circuit with no noise: no syndrome and no valid check may fire.

    Independent of the conjugation argument (a full forward simulation from |0...0>), so it
    also confirms each check's expected sign. It cannot catch a check that is deterministic
    only for the |0> input; `randomized_input_gate` does that.
    """
    stim_circuit = to_stim(circuit, measure=True)
    samples = stim_circuit.compile_sampler(seed=seed).sample(shots=shots)
    registers = _register_samples(circuit, samples)
    rejected = [lane for lane, s in analysis.status.items() if s != "valid"]
    probes = [GaugeCheck(lanes=(lane,), expected=0) for lane in rejected]
    fired, values = _check_values(registers, list(analysis.checks) + probes,
                                  patch_map(circuit).n)
    checks = values[:len(analysis.checks)]
    wrong = sum(int((v != bool(c.expected)).sum()) for c, v in zip(analysis.checks, checks))
    # Rejected candidates that a |0>-input-only test would have accepted: deterministic here.
    trap = sum(1 for v in values[len(analysis.checks):] if not v.any() or v.all())
    return {"noiseless_shots": shots, "noiseless_syndrome_fired": int(fired.sum()),
            "noiseless_check_fired": wrong, "rejected_but_deterministic_at_zero_input": trap}


def _program_randomizer(circuit, program_lanes: Sequence[int], rng: np.random.Generator,
                        rounds: int = 3):
    """
    Physical gates preparing a random stabilizer state on the program lanes from |0bar>:
    the library's own logical H, S and CNOT gadgets on a scratch IcebergSet with the same
    register layout, mapped onto `circuit`'s qubit indices by register name.
    """
    from qiskit import QuantumCircuit

    from iceberg.iceberg_set import IcebergSet

    pm = patch_map(circuit)
    scratch = QuantumCircuit()
    patches = IcebergSet(pm.patches * pm.k, pm.n, scratch)
    lanes = list(program_lanes)
    for _ in range(rounds):
        for lane in lanes:
            choice = rng.integers(4)
            patch, slot = divmod(lane, pm.k)
            if choice in (1, 3):
                patches.H_at(patch, slot)
            if choice in (2, 3):
                patches.S_at(patch, slot)
        order = rng.permutation(lanes)
        for a, b in zip(order[::2], order[1::2]):
            patches.CNOT(int(a), int(b))
    target = {(reg.name, i): circuit.find_bit(q).index
              for reg in circuit.qregs for i, q in enumerate(reg)}
    source = {q: (reg.name, i) for reg in scratch.qregs for i, q in enumerate(reg)}
    import stim

    out = stim.Circuit()
    for inst in scratch.data:
        name = inst.operation.name
        if name == "barrier":
            continue
        qubits = [target[source[q]] for q in inst.qubits]
        out.append(ONE_Q.get(name) or TWO_Q[name], qubits)
    return out


def randomized_input_gate(circuit, analysis: GaugeAnalysis,
                          permutation: Sequence[Tuple[int, int]], *, inputs: int = 8,
                          shots: int = 400, seed: int = 7) -> Dict[str, int]:
    """
    The criterion's claim, tested directly: with the program lanes prepared in random
    stabilizer states (spares still |0bar>), every valid check stays deterministic with
    the same expected bit. Also reports how many *rejected* single-lane candidates would
    have passed a |0>-input-only test but fail here (the post-selection-on-the-answer trap).
    """
    pm = patch_map(circuit)
    start, stop = body_bounds(circuit, pm)
    encoder = to_stim(circuit, 0, start)
    rest = to_stim(circuit, start, None, measure=True)
    program_lanes = sorted({int(p) * pm.k + int(s) for p, s in permutation})
    rejected = [lane for lane, s in analysis.status.items() if s != "valid"]
    probes = [GaugeCheck(lanes=(lane,), expected=0) for lane in rejected]
    rng = np.random.default_rng(seed)
    wrong = 0
    rejected_random = set()
    for draw in range(inputs):
        full = encoder + _program_randomizer(circuit, program_lanes, rng) + rest
        samples = full.compile_sampler(seed=seed + draw).sample(shots=shots)
        registers = _register_samples(circuit, samples)
        fired, values = _check_values(registers, list(analysis.checks) + probes, pm.n)
        if fired.any():
            raise AssertionError("noiseless randomized-input run fired a syndrome")
        for c, v in zip(analysis.checks, values[:len(analysis.checks)]):
            wrong += int((v != bool(c.expected)).sum())
        for lane, v in zip(rejected, values[len(analysis.checks):]):
            if v.any() and not v.all():
                rejected_random.add(lane)
    return {"random_inputs": inputs, "random_input_check_fired": wrong,
            "rejected_candidates": len(rejected),
            "rejected_random_under_random_inputs": len(rejected_random)}
