@dataclass
class DecodedSamples:
    """Per distinct outcome: probability, kept under each rule, reduced logical key."""

    probs: np.ndarray
    kept_422: np.ndarray
    kept_412: np.ndarray
    key_index: np.ndarray          # index into `keys` (reduced, program-qubit order)
    keys: List[str]

    def distribution(self, which: str) -> Tuple[Dict[str, float], float]:
        kept = self.kept_422 if which == "422" else self.kept_412
        total = float(self.probs.sum()) or 1.0
        mass = np.bincount(self.key_index[kept], weights=self.probs[kept],
                           minlength=len(self.keys))
        kept_mass = float(mass.sum())
        norm = kept_mass or 1.0
        dist = {self.keys[i]: float(mass[i] / norm) for i in np.flatnonzero(mass > 0)}
        return dist, kept_mass / total


def _register_columns(key_order: Sequence[str], key_widths: Sequence[int]):
    columns = {}
    offset = 0
    for name, width in zip(key_order, key_widths):
        columns[name] = np.arange(offset, offset + int(width))
        offset += int(width)
    return columns, offset


def decode_samples(dist: Dict[str, float], key_order: Sequence[str],
                   key_widths: Sequence[int], final_positions: Sequence[Tuple[int, int]],
                   checks: Sequence[GaugeCheck], n_code: int) -> DecodedSamples:
    """
    `iceberg_postselect` + `reduce_distribution`, vectorized, plus the gauge checks.

    The [[4,2,2]] path must reproduce the library exactly (checked by the experiment against
    Fig 6's own numbers); the [[4,1,2]] path additionally drops outcomes where a check's
    XOR of decoded lane bits differs from its expected value.
    """
    layout = CodeLayout(n_code)
    k = layout.k
    columns, width = _register_columns(key_order, key_widths)
    keys = list(dist.keys())
    probs = np.fromiter((dist[key] for key in keys), dtype=float, count=len(keys))
    flat = "".join(key.replace(" ", "") for key in keys)
    if len(flat) != width * len(keys):
        raise ValueError("outcome strings do not match the register widths")
    bits = (np.frombuffer(flat.encode("ascii"), dtype=np.uint8) - 48).reshape(len(keys), width)
    bits = bits.astype(bool)

    syndrome = np.zeros(len(keys), dtype=bool)
    for name in key_order:
        if "parity" in name or "flag" in name:
            syndrome |= bits[:, columns[name]].any(axis=1)
    data_names = [name for name in key_order if "data" in name]
    patches = len(data_names)
    logical = np.zeros((len(keys), patches * k), dtype=bool)
    odd = np.zeros(len(keys), dtype=bool)
    for patch, name in enumerate(data_names):
        block = bits[:, columns[name]]
        odd |= (block.sum(axis=1) % 2).astype(bool)
        anchor = block[:, layout.z_anchor]
        for slot in range(k):
            logical[:, patch * k + slot] = block[:, layout.lane(slot)] ^ anchor
    kept_422 = ~syndrome & ~odd
    gauge_ok = np.ones(len(keys), dtype=bool)
    for check in checks:
        parity = np.zeros(len(keys), dtype=bool)
        for lane in check.lanes:
            parity ^= logical[:, lane]
        gauge_ok &= parity == bool(check.expected)
    kept_412 = kept_422 & gauge_ok

    kept_indices = [int(p) * k + int(s) for p, s in final_positions]
    reduced = (logical[:, kept_indices].astype(np.uint8) + 48).tobytes()
    m = len(kept_indices)
    reduced_keys = [reduced[i * m:(i + 1) * m].decode("ascii") for i in range(len(keys))]
    unique: Dict[str, int] = {}
    key_index = np.fromiter((unique.setdefault(key, len(unique)) for key in reduced_keys),
                            dtype=np.int64, count=len(keys))
    return DecodedSamples(probs=probs, kept_422=kept_422, kept_412=kept_412,
                          key_index=key_index, keys=list(unique))


