@dataclass(frozen=True)
class PatchMap:
    """Physical data-qubit indices per patch (patch order = `data_<i>` register index)."""

    data: Tuple[Tuple[int, ...], ...]
    ancillas: Tuple[int, ...]
    num_qubits: int

    @property
    def n(self) -> int:
        return len(self.data[0])

    @property
    def k(self) -> int:
        return self.n - 2

    @property
    def patches(self) -> int:
        return len(self.data)

    @property
    def lanes(self) -> int:
        return self.patches * self.k


def patch_map(circuit) -> PatchMap:
    registers = [r for r in circuit.qregs if r.name.startswith(DATA_REGISTER_PREFIX)]
    registers.sort(key=lambda r: int(r.name[len(DATA_REGISTER_PREFIX):]))
    if [int(r.name[len(DATA_REGISTER_PREFIX):]) for r in registers] != list(range(len(registers))):
        raise ValueError("data registers are not numbered 0..P-1")
    index = {q: i for i, q in enumerate(circuit.qubits)}
    data = tuple(tuple(index[q] for q in reg) for reg in registers)
    owned = {q for patch in data for q in patch}
    ancillas = tuple(q for q in range(circuit.num_qubits) if q not in owned)
    return PatchMap(data=data, ancillas=ancillas, num_qubits=circuit.num_qubits)


def body_bounds(circuit, pm: PatchMap) -> Tuple[int, int]:
    """
    (start, stop) of the logical body: after the encoder's barrier, before the readout.

    Refuses anything but the shape `IcebergSet` emits: per patch h(d0), cx(d0,d1), ...,
    cx(d_{n-2}, d_{n-1}), then one barrier; measurements only at the end (bare mode).
    """
    ops = circuit.data
    index = {q: i for i, q in enumerate(circuit.qubits)}
    expected = []
    for data in pm.data:
        expected.append(("h", (data[0],)))
        expected.extend(("cx", (data[i], data[i + 1])) for i in range(pm.n - 1))
    head = [(inst.operation.name, tuple(index[q] for q in inst.qubits))
            for inst in ops[: len(expected)]]
    if head != expected or ops[len(expected)].operation.name != "barrier":
        raise ValueError("circuit does not start with the IcebergSet encoder and a barrier")
    start = len(expected) + 1
    # Measurements must be terminal per qubit (bare mode: each patch's parity pair is read
    # once its own extraction is done, data qubits last). Then conjugating a final check
    # by every unitary gate is exact: a gate after some other qubit's measurement commutes
    # with that measurement.
    measured = set()
    for inst in ops[start:]:
        qubits = {index[q] for q in inst.qubits}
        if inst.operation.name == "measure":
            if qubits & measured:
                raise ValueError("a qubit is measured twice")
            measured |= qubits
        elif inst.operation.name != "barrier" and qubits & measured:
            raise ValueError("gate after measurement: only bare-mode circuits are supported")
    return start, len(ops)


def to_stim(circuit, start: int = 0, stop: Optional[int] = None, *, measure: bool = False,
            skip_measure: bool = False):
    """
    Gate-for-gate Stim copy of `circuit.data[start:stop]` (no noise, no scheduling).

    `measure` keeps measurements as M; `skip_measure` drops them (the unitary part).
    """
    import stim

    index = {q: i for i, q in enumerate(circuit.qubits)}
    out = stim.Circuit()
    for inst in circuit.data[start:stop]:
        name = inst.operation.name
        qubits = [index[q] for q in inst.qubits]
        if name == "barrier":
            continue
        if name in ONE_Q:
            out.append(ONE_Q[name], qubits)
        elif name in TWO_Q:
            out.append(TWO_Q[name], qubits)
        elif name == "measure" and measure:
            out.append("M", qubits)
        elif name == "measure" and skip_measure:
            continue
        else:
            raise ValueError(f"no Clifford conversion for {name!r}")
    return out


