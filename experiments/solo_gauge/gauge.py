"""
gauge.py -- [[4,1,2]] decoding of solo patches, as post-processing of the same samples.

A patch that holds exactly one program qubit (a *solo* patch) has a spare lane that the
encoder prepares in |0bar>. Keeping it there gauge-fixes [[4,2,2]] into [[4,1,2]]: the
spare's Zbar = Z[z_anchor] Z[lane] joins S_X and S_Z as a third check, and the final
Z-basis data readout already measures it (it is `CodeLayout.decode_logical` of the spare
lane). Nothing physical changes; the decoder simply also discards a shot whose spare bit is
wrong. [[4,1,2]] still has distance 2 (quantum Singleton: n - k >= 2(d - 1) gives d <= 2 at
n = 4, k = 1), so it detects more weight-2 patterns but corrects nothing.

Which checks are valid
----------------------
The translator does not keep spares quiet. A solo H is promoted to a whole-patch HH, which
rotates the spare to |+bar> (so its Zbar is random at the end unless an even number of HH
hit the patch), and a transversal macro can copy a program value into a spare lane. A
check must therefore be *deterministic for every program input state*, not merely for the
|0...0> the benchmark happens to start from: a check that is deterministic only because the
program's ideal state is known would be post-selection on the answer.

Criterion. Let B be the body of the translated circuit (after the encoder, up to the final
measurements). For a final Zbar product P over spare lanes of solo patches, P is a valid
check iff  B^dag P B  lies, up to sign, in the group generated by

    S_X, S_Z of every patch,  Zbar_j of every lane j that held no program qubit at the
    start (it is |0bar> there),  Z on every ancilla (|0> there).

That group is exactly the stabilizer of "code space, spare lanes |0bar>, program lanes in
any state", so membership is necessary and sufficient; the sign is the expected outcome.
The conjugation is done physically with Stim (`PauliString.before`), then decoded into
logical coordinates with the closed-form factorization of `tests/logical_action.py`, so
lane moves (routing SWAPs), HH frame flips and entangling macros are all accounted for.
Products of several candidate lanes are solved for by GF(2) elimination.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from iceberg.layout import DATA_REGISTER_PREFIX, CodeLayout

#: Qiskit -> Stim names for the unitary part of a translated circuit (bare mode, proxies).
ONE_Q = {"h": "H", "x": "X", "y": "Y", "z": "Z", "s": "S", "sdg": "S_DAG", "sx": "SQRT_X",
         "sxdg": "SQRT_X_DAG", "id": "I"}
TWO_Q = {"cx": "CX", "cz": "CZ", "swap": "SWAP"}


