def _pauli(num_qubits: int, sites: Dict[int, str]):
    import stim

    out = stim.PauliString(num_qubits)
    for qubit, letter in sites.items():
        out[qubit] = letter
    return out


def zbar(pm: PatchMap, lane: int):
    """Zbar of global lane `patch * k + slot`, as a physical Pauli."""
    patch, slot = divmod(lane, pm.k)
    layout = CodeLayout(pm.n)
    data = pm.data[patch]
    return _pauli(pm.num_qubits, {data[q]: "Z" for q in layout.z_support(slot)})


def xbar(pm: PatchMap, lane: int):
    patch, slot = divmod(lane, pm.k)
    layout = CodeLayout(pm.n)
    data = pm.data[patch]
    return _pauli(pm.num_qubits, {data[q]: "X" for q in layout.x_support(slot)})


@dataclass
class LogicalImage:
    """A physical Pauli factored as logical part x stabilizers x ancilla part."""

    x: np.ndarray            # (lanes,) bool: logical X component per lane
    z: np.ndarray            # (lanes,) bool: logical Z component per lane
    stab_x: np.ndarray       # (patches,) bool: S_X factor used
    stab_z: np.ndarray       # (patches,) bool: S_Z factor used
    ancilla_x: bool          # X/Y support on a |0> ancilla (random outcome)
    ancilla_z: np.ndarray    # ancilla indices carrying Z


def decode_pauli(pauli, pm: PatchMap) -> LogicalImage:
    """
    Factor a physical Pauli into logical, stabilizer and ancilla parts.

    Per patch, supp(Xbar_i) = {x_anchor, lane_i}, so the z-anchor X bit reads off the S_X
    factor and the lane bits follow by XOR; dually for Z. Raises if the Pauli leaves the
    normalizer (it would anticommute with a stabilizer), which a conjugated check never does.
    """
    xs, zs = pauli.to_numpy()
    layout = CodeLayout(pm.n)
    xa, za = layout.x_anchor, layout.z_anchor
    lanes = np.array(layout.lane_indices())
    P, k = pm.patches, pm.k
    lx = np.zeros(P * k, dtype=bool)
    lz = np.zeros(P * k, dtype=bool)
    sx = np.zeros(P, dtype=bool)
    sz = np.zeros(P, dtype=bool)
    for p, data in enumerate(pm.data):
        data = np.asarray(data)
        x, z = xs[data], zs[data]
        use_x = bool(x[za])
        a = x[lanes] ^ use_x
        if bool(x[xa]) != (bool(a.sum() % 2) ^ use_x):
            raise ValueError(f"Pauli anticommutes with S_Z of patch {p}")
        use_z = bool(z[xa])
        c = z[lanes] ^ use_z
        if bool(z[za]) != (bool(c.sum() % 2) ^ use_z):
            raise ValueError(f"Pauli anticommutes with S_X of patch {p}")
        lx[p * k:(p + 1) * k] = a
        lz[p * k:(p + 1) * k] = c
        sx[p], sz[p] = use_x, use_z
    anc = np.asarray(pm.ancillas, dtype=int)
    ancilla_x = bool(xs[anc].any()) if len(anc) else False
    ancilla_z = anc[zs[anc]] if len(anc) else anc
    return LogicalImage(x=lx, z=lz, stab_x=sx, stab_z=sz, ancilla_x=ancilla_x,
                        ancilla_z=ancilla_z)


def z_check_sign(pauli, image: LogicalImage, pm: PatchMap) -> int:
    """
    +1 or -1: `pauli` = sign * (prod Zbar over image.z) * stabilizers * ancilla Z's.

    Only for images with no logical X part and no ancilla X: then every factor commutes,
    the representative is Hermitian, and it has +1 expectation on the reference state, so
    the sign is the deterministic measured eigenvalue.
    """
    if image.x.any() or image.ancilla_x:
        raise ValueError("not a Z-type check image")
    rep = _pauli(pm.num_qubits, {})
    for lane in np.flatnonzero(image.z):
        rep *= zbar(pm, int(lane))
    for p in np.flatnonzero(image.stab_x):
        rep *= _pauli(pm.num_qubits, {q: "X" for q in pm.data[p]})
    for p in np.flatnonzero(image.stab_z):
        rep *= _pauli(pm.num_qubits, {q: "Z" for q in pm.data[p]})
    for q in image.ancilla_z:
        rep *= _pauli(pm.num_qubits, {int(q): "Z"})
    if pauli == rep:
        return +1
    if pauli == -rep:
        return -1
    raise ValueError(f"sign is not real: {pauli} vs {rep}")


