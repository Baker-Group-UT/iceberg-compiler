@dataclass(frozen=True)
class GaugeCheck:
    """XOR of the decoded bits of `lanes` (global lane indices) must equal `expected`."""

    lanes: Tuple[int, ...]
    expected: int


@dataclass
class GaugeAnalysis:
    patches: int
    k: int
    solo_patches: Tuple[int, ...]
    #: Final-spare lanes of solo patches: the only lanes the user's rule lets us check.
    candidates: Tuple[int, ...]
    #: Per candidate lane, alone: "valid", "x_frame" (spare ends in an X/Y eigenbasis, e.g.
    #: an odd number of HH), or "entangled" (its value depends on a program lane).
    status: Dict[int, str]
    checks: Tuple[GaugeCheck, ...]
    initial_spare: Tuple[int, ...] = ()
    final_spare: Tuple[int, ...] = ()
    detail: Dict[int, str] = field(default_factory=dict)

    @property
    def available(self) -> int:
        return len(self.checks)

    def summary(self) -> Dict[str, object]:
        counts = {s: sum(1 for v in self.status.values() if v == s)
                  for s in ("valid", "x_frame", "entangled")}
        return {
            "patches": self.patches,
            "solo_patches": len(self.solo_patches),
            "candidates": len(self.candidates),
            "checks": len(self.checks),
            "cand_valid": counts["valid"],
            "cand_x_frame": counts["x_frame"],
            "cand_entangled": counts["entangled"],
            "check_lanes": ";".join("+".join(map(str, c.lanes)) + f"={c.expected}"
                                    for c in self.checks),
        }


def solo_patches_of(permutation: Sequence[Tuple[int, int]]) -> Tuple[int, ...]:
    counts: Dict[int, int] = {}
    for patch, _ in permutation:
        counts[int(patch)] = counts.get(int(patch), 0) + 1
    return tuple(sorted(p for p, c in counts.items() if c == 1))


def analyse(circuit, permutation: Sequence[Tuple[int, int]],
            final_positions: Sequence[Tuple[int, int]], *,
            solo_only: bool = True) -> GaugeAnalysis:
    """
    Every valid gauge check of a translated circuit (see the module docstring).

    `permutation` is where each program qubit starts, `final_positions`
    (`context.state_positions`) where it ends. `solo_only=False` lets every final spare
    lane be a candidate (not the user's rule; kept for the packing-density panel).
    """
    pm = patch_map(circuit)
    k = pm.k
    start, stop = body_bounds(circuit, pm)
    body = to_stim(circuit, start, stop, skip_measure=True)

    initial_occupied = {int(p) * k + int(s) for p, s in permutation}
    final_occupied = {int(p) * k + int(s) for p, s in final_positions}
    all_lanes = set(range(pm.lanes))
    initial_spare = sorted(all_lanes - initial_occupied)
    final_spare = sorted(all_lanes - final_occupied)
    solo = solo_patches_of(permutation)
    if solo_only:
        candidates = [lane for lane in final_spare if lane // k in solo]
    else:
        candidates = list(final_spare)

    program_lanes = np.zeros(pm.lanes, dtype=bool)
    program_lanes[sorted(initial_occupied)] = True

    def forbidden(image: LogicalImage) -> np.ndarray:
        return np.concatenate([image.x, image.z & program_lanes, [image.ancilla_x]])

    images = {}
    rows = []
    status: Dict[int, str] = {}
    detail: Dict[int, str] = {}
    for lane in candidates:
        back = zbar(pm, lane).before(body)
        image = decode_pauli(back, pm)
        images[lane] = (back, image)
        f = forbidden(image)
        rows.append(f)
        if not f.any():
            status[lane] = "valid"
        elif (image.x & program_lanes).any() or (image.z & program_lanes).any() or image.ancilla_x:
            status[lane] = "entangled"
        else:
            status[lane] = "x_frame"
        detail[lane] = (f"X on {np.flatnonzero(image.x).tolist()}, "
                        f"Z on {np.flatnonzero(image.z).tolist()}")

    checks: List[GaugeCheck] = []
    if candidates:
        for combo in left_kernel(np.array(rows)):
            lanes = tuple(int(candidates[i]) for i in np.flatnonzero(combo))
            final = _pauli(pm.num_qubits, {})
            for lane in lanes:
                final *= zbar(pm, lane)
            back = final.before(body)
            image = decode_pauli(back, pm)
            if forbidden(image).any():
                raise AssertionError("kernel vector is not a valid check")
            sign = z_check_sign(back, image, pm)
            checks.append(GaugeCheck(lanes=lanes, expected=0 if sign > 0 else 1))
    return GaugeAnalysis(
        patches=pm.patches, k=k, solo_patches=solo, candidates=tuple(candidates),
        status=status, checks=tuple(checks), initial_spare=tuple(initial_spare),
        final_spare=tuple(final_spare), detail=detail,
    )


def analyse_translation(translation, *, solo_only: bool = True) -> GaugeAnalysis:
    return analyse(translation.circuit, translation.permutation,
                   translation.context.state_positions, solo_only=solo_only)


